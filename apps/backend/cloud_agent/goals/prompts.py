"""The two places a goal reaches a model: the turn preamble, and an automatic round.

Both travel the ordinary ``task_prompt`` channel, exactly as selected skills do,
so all five harnesses receive them and the host protocol, the network surface
and the sandbox layout are all untouched.

The preamble is prepended to *every* turn of a conversation with an active goal,
including the human turn that set it — the first turn is the one that should
already be working toward it. The round body is generated by the server for the
automatic rounds; a client cannot forge one because a client never sends one.

Nothing here mentions MCP. The report is the model's own final message, which
every runtime can carry, so a goal works in a conversation that has never
connected a single tool.
"""

from __future__ import annotations

import json
from typing import Any

from cloud_agent.goals.models import MAX_REASON_CHARS, MAX_REPORT_REPAIRS
from cloud_agent.goals.report import (
    GOAL_REPORT_FENCE,
    MAX_EVIDENCE_CHARS,
    MAX_EVIDENCE_ITEMS,
    REPORT_VERSION,
)

#: The report block, spelled out once. The same text reaches a person's turn and
#: an automatic round: a turn that finishes the work should be able to say so
#: whichever kind of turn it was.
REPORT_INSTRUCTIONS = (
    "If and only if you are finishing — the objective is met, or you genuinely "
    "need something from the user that you cannot get inside this workspace — "
    "end your final message with this block, last, with nothing after it:\n"
    f"```{GOAL_REPORT_FENCE}\n"
    f'{{"version":{REPORT_VERSION},"outcome":"complete","reason":"<what was done and how it was verified>",'
    '"evidence":["<command you ran and its result>"]}\n'
    "```\n"
    'Use "needs_input" instead of "complete" when you are blocked on the user, '
    "and put exactly what you need in reason. Anything else — still working, "
    "nothing to report — means no block at all: keep working and say so in prose."
)

#: The bound on the report, stated so that a model does not have to learn it by
#: being refused. Kept next to the parser's constants rather than restated here.
_REPORT_BOUNDS = (
    f"`reason` is required and at most {MAX_REASON_CHARS} characters; "
    f"`evidence` is optional, at most {MAX_EVIDENCE_ITEMS} items, "
    f"each at most {MAX_EVIDENCE_CHARS} characters."
)


def prompt_with_goal(prompt: str, goal: dict[str, Any] | None) -> str:
    """Prefix an active goal to a turn's prompt; pass everything else through.

    ``goal`` is the conversation's goal as the store reads it (``None`` when
    there is none). A goal that is not ``active`` adds nothing: paused and
    complete both mean "this is not being worked toward right now", and a
    preamble promising to judge a report the platform will not judge is worse
    than no preamble at all.
    """
    if not goal or not goal.get("objective") or str(goal.get("state")) != "active":
        return prompt
    header = (
        "<conversation_goal>\n"
        f"Objective: {json.dumps(str(goal['objective']), ensure_ascii=False)}\n"
        # How many rounds have run, and — only when the owner asked for one —
        # how many they allowed. A goal with no stated bound says so by saying
        # nothing about one; printing "3/50" here told the model it was on a
        # budget nobody had set, and told the owner the same thing when the
        # report came back.
        f"Automatic rounds run so far: {_as_int(goal.get('rounds_used'))}"
        f"{_rounds_bound(goal)}\n"
        "This conversation has a completion goal set by the user. Work toward it "
        "in every turn. "
        f"{REPORT_INSTRUCTIONS}\n"
        f"{_REPORT_BOUNDS}\n"
        'Report "complete" only after you have run the check the objective names '
        "and the result is in this turn's own output.\n"
        "</conversation_goal>\n\n"
    )
    return f"{header}{prompt}"


def _rounds_bound(goal: dict[str, Any]) -> str:
    """The owner's own bound, as a clause, or nothing when they set none.

    A goal nobody bounded gets no clause at all rather than a large number: a
    model told "of 999999" plans differently from one told nothing, and the
    former is a limit the owner never chose.
    """
    bound = goal.get("max_rounds")
    if bound is None or isinstance(bound, bool) or not isinstance(bound, int) or bound < 1:
        return ""
    return f" of at most {bound} the user allows"


def _as_int(value: Any) -> int:
    """A counter read back from a row, or zero.

    The goal arrives here as the store's dict rather than as the validated
    model, so the one thing this module must not do is raise on a shape it did
    not expect: a prompt that cannot be built is a turn that cannot run.
    """
    return value if isinstance(value, int) and not isinstance(value, bool) else 0


def render_round_prompt(
    *,
    objective: str,
    round_number: int,
    max_rounds: int | None,
    previous: str | None = None,
    previous_paused: bool = False,
) -> str:
    """The body of one automatic work round, generated server-side.

    ``max_rounds`` is the owner's own bound, or ``None`` when they stated none.
    The unset case is not rendered as a big number: the round says which one it
    is and nothing about a total, because there is no total.

    The workspace line is the one that matters most here: rounds can be hours
    apart and the container may have restarted between them, so a model that
    trusts its own earlier narration over what it can see now is a model that
    reports success against a tree that no longer exists.
    """
    counted = (
        f'round="{round_number}" of="{max_rounds}"'
        if max_rounds is not None
        else f'round="{round_number}"'
    )
    lines = [
        f'<goal_round kind="work" {counted}>',
        "This turn was started by the platform because the conversation has an "
        "active goal. Continue working toward the objective in this same "
        "conversation. Treat the current workspace, tool results and files as "
        "authoritative; inspect them instead of assuming earlier narration is "
        "still current. Make concrete progress and verify the result before "
        "reporting.",
    ]
    if previous and previous_paused:
        lines.append(
            "The goal was paused since the last turn and the user asked for it to "
            f"continue. What was recorded then: {previous}"
        )
    elif previous:
        lines.append(f"What the previous turn reported: {previous}")
    lines.append(f"Objective: {json.dumps(objective, ensure_ascii=False)}")
    lines.append(REPORT_INSTRUCTIONS)
    lines.append(_REPORT_BOUNDS)
    lines.append("</goal_round>")
    return "\n".join(lines)


def render_repair_prompt(*, objective: str, detail: str | None = None) -> str:
    """The body of one bounded report-repair round.

    It is charged to the same budget as any other automatic round, and it exists
    only to restate a report the platform could not read. The instruction not to
    run tools is what keeps it from becoming an unnumbered extra work round; a
    deployment only offers it to a runtime that can be pinned to that, and
    ``repair_supported`` is the caller's check, not a promise made here.
    """
    lines = [
        '<goal_round kind="repair">',
        "Your previous final message ended with a goal report block that the "
        "platform could not read, so this turn is only about restating it.",
        "Do not run more tools and do not do more work. Using what you already "
        "know from this conversation, end this message with the block again, "
        "correctly formatted and last.",
    ]
    if detail:
        lines.append(f"What was wrong with it: {detail}")
    lines.append(f"Objective: {json.dumps(objective, ensure_ascii=False)}")
    lines.append(REPORT_INSTRUCTIONS)
    lines.append(_REPORT_BOUNDS)
    lines.append(f"You get at most {MAX_REPORT_REPAIRS} attempt at this.")
    lines.append("</goal_round>")
    return "\n".join(lines)


