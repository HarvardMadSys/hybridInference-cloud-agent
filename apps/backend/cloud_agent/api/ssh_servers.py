"""Owner routes for SSH servers and each chat's selection of them.

Every response is ``no-store``. No route ever returns a private key: a server
shows its public key and the one-line command that installs it. A check is the
platform dialling an address the owner typed, so checks are serialized per
owner and counted against an hourly limit shared by every replica.
"""

