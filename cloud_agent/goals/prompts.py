"""The two places a goal reaches a model: the turn preamble, and an automatic round.

Both travel the ordinary ``task_prompt`` channel, exactly as selected skills
do, so all five harnesses receive them and the host protocol, the network
surface and the sandbox layout are all untouched.

The preamble is prepended to *every* turn of a conversation with an active goal,
including the human turn that set it — the first turn is the one that should
already be working toward it. The round body is generated by the server for the
automatic rounds; a client cannot forge one because a client never sends one.
"""

from __future__ import annotations

import json
from typing import Any

#: The two lines the model reports with, at the end of its final message. The
#: text path reads them out of the message; the MCP tool writes the same
#: columns, and the decision does not care which happened.
REPORT_INSTRUCTIONS = (
    "End your final message with exactly these two lines:\n"
    "GOAL_STATUS: continue | complete | blocked\n"
    "GOAL_REASON: <one line — what remains, or the evidence of completion, "
    "or the blocker>"
)

#: The same report, as a tool call. Preferred when the harness can reach the
#: relay, because a call is a structured act that lands the moment it happens,
#: while the two lines above are reconstructed from prose at the end of the turn
#: — and a turn that crashes has no prose at all.
REPORT_TOOL_INSTRUCTIONS = (
    "Call the `report_goal` tool (status, reason) instead if your session offers "
    "it: it records the same report the moment you make it. `get_goal` reads the "
    "objective and how many rounds it has used."
)


def with_mcp_availability(goal: dict[str, Any] | None, available: bool) -> dict[str, Any] | None:
    """The conversation's goal, plus whether *this* turn's session can call tools.

    Composed at claim time rather than stored, because it is a fact about the
    turn's harness and not about the goal: the same conversation claimed by two
    runtimes — one that the relay serves and one it does not — must tell each of
    them only about what that one can reach.
    """
    if goal is None:
        return None
    return {**goal, "mcp_available": available}


def prompt_with_goal(prompt: str, goal: dict[str, Any] | None) -> str:
    """Prefix an active goal to a turn's prompt; pass everything else through.

    ``goal`` is the conversation's goal as the store reads it (``None`` when
    there is none). A goal that is not ``active`` adds nothing: paused, blocked
    and complete all mean "this is not being worked toward right now", and a
    preamble promising to judge a report the platform will not judge is worse
    than no preamble at all.
    """
    if not goal or not goal.get("objective") or str(goal.get("state")) != "active":
        return prompt
    rounds_used = _as_int(goal.get("rounds_used"))
    max_rounds = _as_int(goal.get("max_rounds"))
    header = (
        "<conversation_goal>\n"
        f"Objective: {json.dumps(str(goal['objective']), ensure_ascii=False)}\n"
        f"Round: {rounds_used}/{max_rounds} used\n"
        "This conversation has a completion goal set by the user. Work toward "
        "it in every turn. "
        f"{REPORT_TOOL_INSTRUCTIONS if goal.get('mcp_available') else REPORT_INSTRUCTIONS}\n"
        'Report "complete" only after you have run the check the objective '
        "names and the result is in this turn's output. "
        'Report "blocked" only for a condition you cannot change from inside '
        'this workspace; the platform accepts "blocked" only after it has '
        "been reported in three consecutive turns.\n"
    )
    return f"{header}</conversation_goal>\n\n{prompt}"


def _as_int(value: Any) -> int:
    """A counter read back from a row, or zero.

    The goal arrives here as the store's dict rather than as the validated
    model, so the one thing this module must not do is raise on a shape it did
    not expect: a prompt that cannot be built is a turn that cannot run.
    """
    return value if isinstance(value, int) and not isinstance(value, bool) else 0


def _previous_block(reason: str | None) -> str:
    """Tell the next round that its predecessor's blocked claim was not accepted."""
    if not reason:
        return (
            "Your previous turn reported blocked, and the platform has not "
            "accepted it yet. Try a different approach, or gather the evidence "
            "that the condition truly cannot be changed from inside this workspace."
        )
    return (
        f"Your previous turn reported blocked: {reason}\n"
        "The platform has not accepted it yet; try a different approach or "
        "gather evidence that it cannot be done."
    )


def render_round_prompt(
    *,
    objective: str,
    kind: str,
    round_number: int,
    max_rounds: int,
    previous: str | None = None,
    previous_blocked: bool = False,
) -> str:
    """The body of one automatic round, generated server-side.

    The workspace line is the one that matters most here: rounds can be hours
    apart and the container may have restarted between them, so a model that
    trusts its own earlier narration over what it can see now is a model that
    reports success against a tree that no longer exists.
    """
    if kind == "verify":
        return (
            '<goal_round kind="verify">\n'
            "The previous turn reported the objective complete. This turn is "
            "verification only: re-run the check the objective names, from a "
            "clean state, and do not modify code. If the check passes, report "
            "GOAL_STATUS: complete with the command and its result as the reason. "
            "If it fails, report GOAL_STATUS: continue and state exactly what is "
            "still missing.\n"
            f"Objective: {json.dumps(objective, ensure_ascii=False)}\n"
            "</goal_round>"
        )
    lines = [
        f'<goal_round kind="work" round="{round_number}" of="{max_rounds}">',
        "Continue working toward the objective in this same conversation. Treat the",
        "current workspace, tool results, and files as authoritative; inspect them",
        "instead of assuming earlier narration is still current. Make concrete",
        "progress and verify the result before reporting.",
    ]
    if previous_blocked:
        lines.append(_previous_block(previous))
    elif previous:
        lines.append(f"The previous turn reported: {previous}")
    lines.append(f"Objective: {json.dumps(objective, ensure_ascii=False)}")
    lines.append("</goal_round>")
    return "\n".join(lines)
