#!/bin/sh
set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPO_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd)
ENV_FILE="$SCRIPT_DIR/.env.local"
PROJECT_NAME=freeinference-local

if command -v docker-compose >/dev/null 2>&1; then
  COMPOSE=docker-compose
elif docker compose version >/dev/null 2>&1; then
  COMPOSE='docker compose'
else
  echo "Docker Compose is required (docker-compose or docker compose)." >&2
  exit 1
fi

compose() {
  # Intentional word splitting: COMPOSE is either one command or `docker compose`.
  # shellcheck disable=SC2086
  $COMPOSE --env-file "$ENV_FILE" --project-name "$PROJECT_NAME" \
    -f "$REPO_ROOT/deploy/control-plane/docker-compose.yml" \
    -f "$SCRIPT_DIR/docker-compose.yml" "$@"
}

random_hex() {
  openssl rand -hex 32
}

ensure_env() {
  if [ -f "$ENV_FILE" ]; then
    return
  fi
  umask 077
  postgres_password=$(random_hex)
  dispatch_token=$(random_hex)
  enroll_token=$(random_hex)
  enroll_hash=$(printf '%s' "$enroll_token" | openssl dgst -sha256 -r | awk '{print $1}')
  session_secret=$(random_hex)
  control_secret=$(random_hex)
  source_secret=$(random_hex)
  dispatcher_token=$(random_hex)
  broker_token=$(random_hex)

  {
    printf '%s\n' \
      '# Generated by deploy/local/dev.sh. Local-only; never commit this file.' \
      'AGENT_POSTGRES_USER=cloudagent' \
      'AGENT_POSTGRES_DB=cloudagent' \
      "AGENT_POSTGRES_PASSWORD=$postgres_password" \
      "AGENT_DATABASE_URL=postgresql://cloudagent:$postgres_password@postgres:5432/cloudagent" \
      'GATEWAY_BASE_URL=http://local-gateway:8080' \
      'GATEWAY_JWKS_URL=http://local-gateway:8080/v1/identity/jwks' \
      "GATEWAY_GRANT_DISPATCH_TOKEN=$dispatch_token" \
      "AGENT_SESSION_SECRET=$session_secret" \
      "AGENT_CONTROL_TOKEN_SECRET=$control_secret" \
      "AGENT_SOURCE_CONTROL_ENCRYPTION_KEY=$source_secret" \
      "AGENT_DISPATCHER_TOKEN=$dispatcher_token" \
      "AGENT_WORKSPACE_BROKER_TOKEN=$broker_token" \
      "LOCAL_ENROLL_TOKEN=$enroll_token" \
      "LOCAL_ENROLL_TOKEN_SHA256=$enroll_hash" \
      'AGENT_SESSION_COOKIE_SECURE=false' \
      'AGENT_REPO_ALLOWLIST=local/demo' \
      'AGENT_SANDBOX_MCP_URL=http://mcp-relay:8001' \
      'AGENT_BROKER_URL_ALLOWED_HOSTS=workspace-broker' \
      'AGENT_NETWORK_NAME=freeinference-local-control' \
      'AGENT_CONTROL_PLANE_BIND=127.0.0.1' \
      'AGENT_CONTROL_PLANE_PORT=18000' \
      'AGENT_MCP_RELAY_BIND=127.0.0.1' \
      'AGENT_MCP_RELAY_PORT=18001' \
      'AGENT_WEB_BIND=127.0.0.1' \
      'AGENT_WEB_PORT=13003' \
      'LOCAL_EDGE_PORT=13002' \
      'AGENT_WEB_BASE_PATH=' \
      'AGENT_WEB_API_URL=/api' \
      'AGENT_WEB_GATEWAY_AUTHORIZE_URL=/authorize' \
      'AGENT_WEB_APP_NAME=FreeInference Cloud Agent (local)' \
      'LOCAL_CHAT_IDLE_TIMEOUT_S=60' \
      'LOCAL_AGENT_TIMEOUT_S=600' \
      'AGENT_RETAINED_DOCKER_DATA_ROOT=/var/lib/docker'
  } >"$ENV_FILE"
  echo "Generated $ENV_FILE with local-only random credentials."
}

wait_ready() {
  attempts=0
  until curl --fail --silent --show-error "http://127.0.0.1:13002/health" >/dev/null \
    && curl --fail --silent --show-error "http://127.0.0.1:13002/api/healthz" >/dev/null; do
    attempts=$((attempts + 1))
    if [ "$attempts" -ge 90 ]; then
      echo "Local stack did not become ready. Recent logs:" >&2
      compose logs --tail=120 >&2
      return 1
    fi
    sleep 2
  done
}

command=${1:-up}
case "$command" in
  up)
    ensure_env
    compose build sandbox-image
    compose up --detach --build
    wait_ready
    echo "Local Cloud Agent is ready: http://127.0.0.1:13002"
    echo "Run '$0 smoke' for an automated login/config/agent lifecycle check."
    ;;
  start)
    ensure_env
    compose start
    wait_ready
    echo "Local Cloud Agent is ready: http://127.0.0.1:13002"
    ;;
  stop)
    ensure_env
    compose stop
    ;;
  status|ps)
    ensure_env
    compose ps
    ;;
  logs)
    ensure_env
    shift || true
    compose logs --follow --tail=150 "$@"
    ;;
  smoke)
    ensure_env
    wait_ready
    exec python3 "$SCRIPT_DIR/smoke.py" "${2:-http://127.0.0.1:13002}"
    ;;
  legacy-smoke)
    ensure_env
    wait_ready
    base_url=${2:-http://127.0.0.1:13002}
    if [ -d /private/tmp ]; then
      # Docker Desktop/Colima shares /private/tmp, but not macOS's per-user
      # /private/var/folders/... value of TMPDIR.
      legacy_tmp_base=/private/tmp
    else
      legacy_tmp_base=${TMPDIR:-/tmp}
    fi
    legacy_root=$(mktemp -d "$legacy_tmp_base/freeinference-legacy-smoke.XXXXXX")
    legacy_root=$(CDPATH= cd -- "$legacy_root" && pwd -P)
    legacy_runner_stopped=0
    legacy_job_id=
    legacy_verified=0
    cleanup_legacy_smoke() {
      if [ -n "$legacy_job_id" ] && [ "$legacy_verified" -eq 0 ]; then
        python3 "$SCRIPT_DIR/legacy_smoke.py" cancel "$base_url" "$legacy_job_id" \
          >/dev/null 2>&1 || true
      fi
      if [ "$legacy_runner_stopped" -eq 1 ]; then
        compose start runner >/dev/null 2>&1 || true
      fi
      case "$legacy_root" in
        */freeinference-legacy-smoke.*)
          rm -rf -- "$legacy_root"
          ;;
      esac
    }
    trap cleanup_legacy_smoke EXIT
    trap 'exit 130' INT TERM

    # A queued job must be claimed only by the explicitly default-off runner
    # below.  The temporary same-path bind models the production mixed-mode
    # host mount; it is test data and is removed on every exit.
    legacy_runner_stopped=1
    compose stop runner
    legacy_job_id=$(python3 "$SCRIPT_DIR/legacy_smoke.py" create "$base_url")
    compose run --rm --no-deps \
      -e AGENT_RESTARTABLE_SANDBOX=0 \
      -e AGENT_RESTARTABLE_RUNTIMES= \
      -v "$legacy_root:$legacy_root" \
      runner python -m cloud_agent_host.runner \
      --workdir "$legacy_root/workspace" --host local-docker
    python3 "$SCRIPT_DIR/legacy_smoke.py" verify "$base_url" "$legacy_job_id"
    legacy_verified=1

    compose start runner
    legacy_runner_stopped=0
    trap - EXIT INT TERM
    cleanup_legacy_smoke
    ;;
  config)
    ensure_env
    compose config --quiet
    echo "Local Compose configuration is valid."
    ;;
  *)
    echo "Usage: $0 {up|start|stop|status|logs [service]|smoke|legacy-smoke|config}" >&2
    exit 2
    ;;
esac
